# ---------------------------------------------------------------------------
# Layout / palette
# ---------------------------------------------------------------------------
W, H = 1200, 675
BG = (15, 27, 45)          # deep navy
HEADER_BG = (15, 27, 45)
CARD_BG = (255, 255, 255)
CARD_LINE = (214, 222, 232)
INK = (16, 32, 54)
MUTED = (90, 104, 122)
ACCENT = (198, 40, 40)     # news red
GOLD = (212, 160, 60)
TAG_BG = (232, 240, 248)
TAG_INK = (23, 68, 120)

MARGIN = 36
HEADER_H = 128
FOOTER_H = 34
GAP = 16
COLS, ROWS = 2, 3


def font(name: str, size: int) -> ImageFont.FreeTypeFont:
    """Pick DejaVu Sans (present on this machine), fall back to Liberation."""
    candidates = [
        f"/usr/share/fonts/truetype/dejavu/DejaVuSans{'-Bold' if name == 'bold' else ''}.ttf",
        f"/usr/share/fonts/truetype/liberation/LiberationSans{'-Bold' if name == 'bold' else '-Regular'}.ttf",
    ]
    for path in candidates:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default()


def wrap(draw: ImageDraw.ImageDraw, text: str, fnt, max_w: int):
    """Greedy word-wrap using real pixel widths."""
    words, lines, cur = text.split(), [], ""
    for word in words:
        trial = f"{cur} {word}".strip()
        if draw.textlength(trial, font=fnt) <= max_w:
            cur = trial
        else:
            if cur:
                lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def draw_card(draw, x, y, w, h, story):
    draw.rounded_rectangle([x, y, x + w, y + h], radius=12,
                           fill=CARD_BG, outline=CARD_LINE, width=1)
    pad = 16
    cx, cy = x + pad, y + 12

    # Number badge
    badge_r = 15
    draw.ellipse([cx, cy, cx + 2 * badge_r, cy + 2 * badge_r], fill=ACCENT)
    num_font = font("bold", 16)
    tw = draw.textlength(story["num"], font=num_font)
    draw.text((cx + badge_r - tw / 2, cy + 5), story["num"],
              font=num_font, fill=(255, 255, 255))

    # Category tag
    tag_font = font("bold", 13)
    tag = story["tag"]
    tag_w = draw.textlength(tag, font=tag_font) + 16
    tx = cx + 2 * badge_r + 10
    draw.rounded_rectangle([tx, cy + 2, tx + tag_w, cy + 26], radius=6, fill=TAG_BG)
    draw.text((tx + 8, cy + 6), tag, font=tag_font, fill=TAG_INK)

    # Headline (up to 2 lines)
    head_font = font("bold", 21)
    text_w = w - 2 * pad
    lines = wrap(draw, story["headline"], head_font, text_w)[:2]
    hy = cy + 38
    for line in lines:
        draw.text((cx, hy), line, font=head_font, fill=INK)
        hy += 26

    # Summary (up to 2 lines, so it never collides with the source line)
    body_font = font("regular", 16)
    slines = wrap(draw, story["summary"], body_font, text_w)[:2]
    sy = hy + 2
    for line in slines:
        draw.text((cx, sy), line, font=body_font, fill=(52, 68, 88))
        sy += 21

    # Source, pinned to the card bottom
    src_font = font("regular", 13)
    draw.text((cx, y + h - 26), f"Source: {story['source']}",
              font=src_font, fill=MUTED)


def main() -> None:
    ap = argparse.ArgumentParser(description="Render the 20 Nov 2026 news image.")
    ap.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT,
                    help="output PNG path (default: news-2026-11-20.png)")
    args = ap.parse_args()

    img = Image.new("RGB", (W, H), BG)
    draw = ImageDraw.Draw(img)

    # --- header ------------------------------------------------------------
    draw.rectangle([0, 0, W, 4], fill=ACCENT)  # red top rule
    draw.text((MARGIN, 22), DATE_LINE, font=font("bold", 15), fill=GOLD)
    draw.text((MARGIN, 44), TITLE, font=font("bold", 44), fill=(255, 255, 255))
    draw.text((MARGIN, 96), SUBTITLE, font=font("regular", 18), fill=(178, 192, 208))
    # "6 stories" chip, top right
    chip = "6 STORIES  •  1 DAY"
    chip_font = font("bold", 14)
    chip_w = draw.textlength(chip, font=chip_font) + 28
    chip_x = W - MARGIN - chip_w
    draw.rounded_rectangle([chip_x, 30, chip_x + chip_w, 62], radius=16,
                           outline=GOLD, width=2)
    draw.text((chip_x + 14, 38), chip, font=chip_font, fill=GOLD)

    # --- cards -------------------------------------------------------------
    grid_top = HEADER_H
    grid_h = H - HEADER_H - FOOTER_H
    card_w = (W - 2 * MARGIN - (COLS - 1) * GAP) // COLS
    card_h = (grid_h - (ROWS - 1) * GAP) // ROWS
    for i, story in enumerate(STORIES):
        r, c = divmod(i, COLS)
        x = MARGIN + c * (card_w + GAP)
        y = grid_top + r * (card_h + GAP)
        draw_card(draw, x, y, card_w, card_h, story)

    # --- footer ------------------------------------------------------------
    foot_font = font("regular", 13)
    draw.text((MARGIN, H - FOOTER_H + 8), FOOTER, font=foot_font, fill=(150, 164, 180))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    img.save(args.output, "PNG")
    print(f"Wrote {args.output}  ({W}x{H}, {args.output.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
